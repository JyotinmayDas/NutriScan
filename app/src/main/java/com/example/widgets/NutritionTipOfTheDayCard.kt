    fun getCategories(): List<String> =
        listOf("Daily Pick") + tipsCatalog.map { it.category }.distinct()

    fun getBookmarkedTipIds(context: Context): Set<String> {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        return prefs.getStringSet(KEY_BOOKMARKED_IDS, emptySet())?.toSet() ?: emptySet()
    }

    fun toggleBookmarkTip(context: Context, tipId: String): Set<String> {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val current = getBookmarkedTipIds(context).toMutableSet()
        if (tipId in current) {
            current.remove(tipId)
        } else {
            current.add(tipId)
        }
        prefs.edit().putStringSet(KEY_BOOKMARKED_IDS, current).apply()
        return current
    }

    fun isTipPracticedOnDate(context: Context, dateKey: String): Boolean {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val dates = prefs.getStringSet(KEY_PRACTICED_DATES, emptySet()).orEmpty()
        return dateKey in dates
    }

    fun markTipPracticedOnDate(context: Context, dateKey: String): Boolean {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val dates = prefs.getStringSet(KEY_PRACTICED_DATES, emptySet()).orEmpty().toMutableSet()
        val isNew = dates.add(dateKey)
        if (isNew) {
            prefs.edit().putStringSet(KEY_PRACTICED_DATES, dates).apply()
            // Award +15 Bonus XP in UserLevelManager
            val xpPrefs = context.getSharedPreferences("nutriscan_xp_level_prefs", Context.MODE_PRIVATE)
            val currentBonus = xpPrefs.getInt("claimed_bonus_xp", 0)
            xpPrefs.edit().putInt("claimed_bonus_xp", currentBonus + 15).apply()
            UserLevelManager.loadBonusXp(context)
        }
        return isNew
    }

    /**
     * Selects the deterministic Tip of the Day index for the given dateKey,
     * prioritizing a nutrition-gap-relevant tip if the user is low on protein, fiber, or water.
     */
    fun getRecommendedTipIndexForDay(
        dateKey: String,
        profile: UserProfile,
        todayEntries: List<FoodDiaryEntry>,
        todayWaterMl: Int
    ): Int {
        if (tipsCatalog.isEmpty()) return 0
        val totalProtein = todayEntries.sumOf { it.protein }
        val totalFiber = todayEntries.sumOf { it.fiber }

        // If the user has logged meals today and has a clear gap, surface a relevant tip first
        if (todayEntries.isNotEmpty()) {
            if (totalProtein < profile.effectiveProteinGoalG() * 0.45) {
                val idx = tipsCatalog.indexOfFirst { it.category == "Protein & Satiety" }
                if (idx >= 0) return idx
            }
            if (totalFiber < profile.effectiveFiberGoalG() * 0.40) {
                val idx = tipsCatalog.indexOfFirst { it.category == "Glycemic Balance" }
                if (idx >= 0) return idx
            }
            if (todayWaterMl < profile.dailyWaterGoalMl * 0.40) {
                val idx = tipsCatalog.indexOfFirst { it.category == "Hydration Science" }
                if (idx >= 0) return idx
            }
        }

        val hash = abs(dateKey.hashCode())
        return hash % tipsCatalog.size
    }

    fun getFallbackAiTip(
        dateKey: String,
        profile: UserProfile,
        todayEntries: List<FoodDiaryEntry>,
        todayWaterMl: Int
    ): AiPersonalizedNutritionTip {
        val idx = getRecommendedTipIndexForDay(dateKey, profile, todayEntries, todayWaterMl)
        val catTip = tipsCatalog.getOrElse(idx) { tipsCatalog.first() }
        return AiPersonalizedNutritionTip(
            id = catTip.id,
            title = catTip.titleEn,
            category = catTip.category,
            emoji = catTip.emoji,
            advice = catTip.adviceEn,
            scientificRationale = catTip.scientificEvidence,
            microAction = catTip.microHabitAction,
            sourceCitation = catTip.sourceCitation,
            personalizedHighlight = "Curated for ${profile.fitnessGoal}",
            dateKey = dateKey,
            isAiGenerated = false
        )
    }
