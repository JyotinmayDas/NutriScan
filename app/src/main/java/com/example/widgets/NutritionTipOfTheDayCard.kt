                        .border(1.dp, FreshGreenPrimary.copy(alpha = 0.28f), RoundedCornerShape(20.dp))
                        .padding(16.dp)
                ) {
                    Column(verticalArrangement = Arrangement.spacedBy(10.dp)) {
                        Row(
                            modifier = Modifier.fillMaxWidth(),
                            horizontalArrangement = Arrangement.SpaceBetween,
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            Surface(
                                shape = RoundedCornerShape(50),
                                color = DarkCharcoalText
                            ) {
                                Text(
                                    text = "$activeEmoji  ${activeCategory.uppercase()}",
                                    style = MaterialTheme.typography.labelSmall,
                                    fontWeight = FontWeight.ExtraBold,
                                    color = LimeAccentStrong,
                                    modifier = Modifier.padding(horizontal = 10.dp, vertical = 4.dp)
                                )
                            }

                            if (viewMode == 0) {
                                // Regenerate Button for AI Tip
                                Surface(
                                    shape = RoundedCornerShape(50),
                                    color = Color.White.copy(alpha = 0.9f),
                                    modifier = Modifier
                                        .clickable(enabled = !isLoadingAiTip) { handleRegenerateWithGemini() }
                                        .testTag("regenerate_ai_tip_button")
                                ) {
                                    Row(
                                        modifier = Modifier.padding(horizontal = 8.dp, vertical = 4.dp),
                                        verticalAlignment = Alignment.CenterVertically,
                                        horizontalArrangement = Arrangement.spacedBy(4.dp)
                                    ) {
                                        if (isLoadingAiTip) {
                                            CircularProgressIndicator(
                                                color = FreshGreenPrimary,
                                                strokeWidth = 1.5.dp,
                                                modifier = Modifier.size(12.dp)
                                            )
                                        } else {
                                            Icon(
                                                imageVector = Icons.Default.Refresh,
                                                contentDescription = "Regenerate Tip with Gemini",
                                                tint = DarkCharcoalText,
                                                modifier = Modifier.size(13.dp)
                                            )
                                        }
                                        Text(
                                            text = if (isLoadingAiTip) "Thinking..." else "New AI Tip",
                                            style = MaterialTheme.typography.labelSmall,
                                            fontWeight = FontWeight.ExtraBold,
                                            color = DarkCharcoalText,
                                            fontSize = 10.sp
                                        )
                                    }
                                }
                            } else {
                                // Previous / Next Catalog Navigation Controls
                                Row(
                                    verticalAlignment = Alignment.CenterVertically,
                                    horizontalArrangement = Arrangement.spacedBy(4.dp)
                                ) {
                                    Surface(
                                        shape = CircleShape,
                                        color = Color.White.copy(alpha = 0.85f),
                                        modifier = Modifier
                                            .size(30.dp)
                                            .clickable {
                                                catalogIndex = if (safeIndex > 0) safeIndex - 1 else filteredTips.size - 1
                                                statusMessage = null
                                            }
                                            .testTag("prev_nutrition_tip_button")
                                    ) {
                                        Box(contentAlignment = Alignment.Center) {
                                            Icon(
                                                imageVector = Icons.AutoMirrored.Filled.KeyboardArrowLeft,
                                                contentDescription = "Previous Tip",
                                                tint = DarkCharcoalText,
                                                modifier = Modifier.size(18.dp)
                                            )
                                        }
                                    }
                                    Surface(
                                        shape = CircleShape,
                                        color = Color.White.copy(alpha = 0.85f),
                                        modifier = Modifier
                                            .size(30.dp)
                                            .clickable {
                                                catalogIndex = (safeIndex + 1) % filteredTips.size.coerceAtLeast(1)
                                                statusMessage = null
                                            }
                                            .testTag("next_nutrition_tip_button")
                                    ) {
                                        Box(contentAlignment = Alignment.Center) {
                                            Icon(
                                                imageVector = Icons.AutoMirrored.Filled.KeyboardArrowRight,
                                                contentDescription = "Next Tip",
                                                tint = DarkCharcoalText,
                                                modifier = Modifier.size(18.dp)
                                            )
                                        }
                                    }
                                }
                            }
                        }

                        // Tip Headline
                        Text(
                            text = activeTitle,
                            style = MaterialTheme.typography.titleMedium,
                            fontWeight = FontWeight.ExtraBold,
                            color = DarkCharcoalText
                        )

                        // Main Evidence-Based Advice Paragraph
                        Text(
                            text = activeAdvice,
                            style = MaterialTheme.typography.bodyMedium,
                            color = DarkCharcoalText.copy(alpha = 0.88f),
                            lineHeight = 20.sp
                        )

                        // Actionable Micro-Habit Box
                        Surface(
                            shape = RoundedCornerShape(14.dp),
                            color = Color.White.copy(alpha = 0.88f),
                            modifier = Modifier.fillMaxWidth()
                        ) {
                            Row(
                                modifier = Modifier.padding(horizontal = 12.dp, vertical = 10.dp),
                                verticalAlignment = Alignment.CenterVertically
                            ) {
                                Icon(
                                    imageVector = Icons.Default.Verified,
                                    contentDescription = null,
                                    tint = FreshGreenPrimary,
                                    modifier = Modifier.size(18.dp)
                                )
                                Spacer(modifier = Modifier.width(8.dp))
                                Column {
                                    Text(
                                        text = "TRY THIS TODAY",
                                        style = MaterialTheme.typography.labelSmall,
                                        fontWeight = FontWeight.ExtraBold,
                                        color = FreshGreenPrimary
                                    )
                                    Text(
                                        text = activeMicroHabit,
                                        style = MaterialTheme.typography.bodySmall,
                                        fontWeight = FontWeight.Bold,
                                        color = DarkCharcoalText
                                    )
                                }
                            }
                        }

                        // Scientific Evidence & Source Citation
                        AnimatedVisibility(visible = showScientificEvidence) {
                            Surface(
                                shape = RoundedCornerShape(14.dp),
                                color = DarkCharcoalText.copy(alpha = 0.07f),
                                modifier = Modifier
                                    .fillMaxWidth()
                                    .clickable { showScientificEvidence = !showScientificEvidence }
                            ) {
                                Row(
                                    modifier = Modifier.padding(horizontal = 12.dp, vertical = 9.dp),
                                    verticalAlignment = Alignment.Top
                                ) {
                                    Icon(
                                        imageVector = Icons.Default.Science,
                                        contentDescription = null,
                                        tint = DarkCharcoalText.copy(alpha = 0.75f),
                                        modifier = Modifier
                                            .size(16.dp)
                                            .padding(top = 2.dp)
                                    )
                                    Spacer(modifier = Modifier.width(8.dp))
                                    Column(verticalArrangement = Arrangement.spacedBy(2.dp)) {
                                        Text(
                                            text = "Why It Works: $activeScience",
                                            style = MaterialTheme.typography.labelSmall,
                                            color = DarkCharcoalText.copy(alpha = 0.85f),
                                            fontWeight = FontWeight.SemiBold
                                        )
                                        Text(
                                            text = "Source: $activeCitation",
                                            style = MaterialTheme.typography.labelSmall,
                                            color = DarkCharcoalText.copy(alpha = 0.65f)
                                        )
                                    }
                                }
                            }
                        }
                    }
                }
            }

            if (statusMessage != null) {
                Surface(
                    shape = RoundedCornerShape(12.dp),
                    color = PastelGreenCard,
                    modifier = Modifier.fillMaxWidth()
                ) {
                    Text(
                        text = statusMessage.orEmpty(),
                        style = MaterialTheme.typography.labelMedium,
                        fontWeight = FontWeight.ExtraBold,
                        color = DarkCharcoalText,
                        modifier = Modifier.padding(horizontal = 12.dp, vertical = 8.dp)
                    )
                }
            }

            if (aiErrorMessage != null) {
                Surface(
                    shape = RoundedCornerShape(12.dp),
                    color = MaterialTheme.colorScheme.errorContainer.copy(alpha = 0.4f),
                    modifier = Modifier.fillMaxWidth()
                ) {
                    Row(
                        modifier = Modifier.padding(horizontal = 12.dp, vertical = 8.dp),
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.SpaceBetween
                    ) {
                        Text(
                            text = aiErrorMessage.orEmpty(),
                            style = MaterialTheme.typography.labelSmall,
                            color = MaterialTheme.colorScheme.error,
                            modifier = Modifier.weight(1f)
                        )
                        IconButton(
                            onClick = { handleRegenerateWithGemini() },
                            modifier = Modifier.size(24.dp)
                        ) {
                            Icon(
                                imageVector = Icons.Default.Refresh,
                                contentDescription = "Retry Gemini",
                                tint = MaterialTheme.colorScheme.error,
                                modifier = Modifier.size(16.dp)
                            )
                        }
                    }
                }
            }

            // 4. Bottom Action Row: Practice Habit (+15 XP) | Ask Coach
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.spacedBy(10.dp)
            ) {
                if (onAskCoachAboutTip != null) {
                    OutlinedButton(
                        onClick = { onAskCoachAboutTip(activeTitle) },
                        shape = RoundedCornerShape(50),
                        modifier = Modifier
                            .weight(1f)
                            .height(46.dp)
                            .testTag("ask_coach_about_tip_button")
                    ) {
                        Icon(
                            imageVector = Icons.Default.AutoAwesome,
                            contentDescription = null,
                            tint = FreshGreenPrimary,
                            modifier = Modifier.size(16.dp)
                        )
                        Spacer(modifier = Modifier.width(6.dp))
                        Text(
                            text = "Ask AI Coach",
                            fontWeight = FontWeight.Bold,
                            maxLines = 1
                        )
                    }
                } else {
                    OutlinedButton(
                        onClick = {
                            if (viewMode == 0) {
                                handleRegenerateWithGemini()
                            } else {
                                catalogIndex = (safeIndex + 1) % filteredTips.size.coerceAtLeast(1)
                            }
                        },
                        shape = RoundedCornerShape(50),
                        modifier = Modifier
                            .weight(1f)
                            .height(46.dp)
                    ) {
                        Text(
                            text = if (viewMode == 0) "New Tip" else "Next Tip →",
                            fontWeight = FontWeight.Bold,
                            maxLines = 1
                        )
                    }
                }

                Button(
                    onClick = {
                        if (!isPracticedToday) {
                            val awarded = NutritionTipRepository.markTipPracticedOnDate(context, selectedDateKey)
                            isPracticedToday = true
                            if (awarded) {
                                statusMessage = "🎉 Awesome! You practiced today's habit and earned +15 Bonus XP!"
                            }
                        } else {
                            if (viewMode == 0) {
                                handleRegenerateWithGemini()
                            } else {
                                catalogIndex = (safeIndex + 1) % filteredTips.size.coerceAtLeast(1)
                                statusMessage = "Viewing Tip ${(safeIndex + 1) % filteredTips.size + 1} of ${filteredTips.size}"
                            }
                        }
                    },
                    shape = RoundedCornerShape(50),
                    colors = ButtonDefaults.buttonColors(
                        containerColor = if (isPracticedToday) FreshGreenPrimary else DarkCharcoalText,
                        contentColor = Color.White
                    ),
                    modifier = Modifier
                        .weight(1.25f)
                        .height(46.dp)
                        .testTag("practice_daily_tip_button")
                ) {
                    Icon(
                        imageVector = if (isPracticedToday) Icons.Default.CheckCircle else Icons.Default.Bolt,
                        contentDescription = null,
                        tint = if (isPracticedToday) Color.White else LimeAccentStrong,
                        modifier = Modifier.size(16.dp)
                    )
                    Spacer(modifier = Modifier.width(6.dp))
                    Text(
                        text = if (isPracticedToday) "Practiced (+15 XP ✓)" else "Apply Today (+15 XP)",
                        fontWeight = FontWeight.ExtraBold,
                        maxLines = 1,
                        overflow = TextOverflow.Ellipsis
                    )
                }
            }
        }
    }
}

/**
 * Daily Nutrition Tip Widget
 * Fetches one personalized, AI-generated nutrition tip each day using the Gemini API
 * and displays it in a clean card format.
 */
@Composable
fun DailyNutritionTipWidget(
    profile: UserProfile,
    todayEntries: List<FoodDiaryEntry>,
    todayWaterMl: Int,
    selectedDateKey: String = todayDateKey(),
    onAskCoachAboutTip: ((String) -> Unit)? = null,
    modifier: Modifier = Modifier
) {
    NutritionTipOfTheDayCard(
        profile = profile,
        todayEntries = todayEntries,
        todayWaterMl = todayWaterMl,
        selectedDateKey = selectedDateKey,
        onAskCoachAboutTip = onAskCoachAboutTip,
        modifier = modifier
    )
}
