        "hi" -> adviceHi
        else -> adviceEn
    }
}

/**
 * Domain model representing a personalized Daily Nutrition Tip generated by Gemini 3.8 Flash.
 */
data class AiPersonalizedNutritionTip(
    val id: String,
    val title: String,
    val category: String,
    val emoji: String,
    val advice: String,
    val scientificRationale: String,
    val microAction: String,
    val sourceCitation: String,
    val personalizedHighlight: String,
    val dateKey: String,
    val isAiGenerated: Boolean = true
)

/**
 * Service that uses Gemini 3.8 Flash via Firebase AI Logic to produce structured,
 * personalized Daily Nutrition Tips based on user logs and calorie/macro goals.
 */
object DailyNutritionTipGeminiService {
    private val tipResponseSchema = Schema.obj(
        properties = mapOf(
            "title" to Schema.string(description = "Catchy, encouraging headline for the daily personalized nutrition tip"),
            "category" to Schema.string(description = "Category: Hydration, Protein & Satiety, Glycemic Balance, Micronutrient Synergy, Gut Health, or Mindful Habits"),
            "emoji" to Schema.string(description = "Single relevant emoji icon representing this tip"),
            "advice" to Schema.string(description = "2-3 sentences of clear, practical advice referencing the user's specific daily metrics and goals"),
            "scientific_rationale" to Schema.string(description = "1 sentence explaining the metabolic or nutritional science behind why this habit works"),
            "micro_action" to Schema.string(description = "One concrete micro-habit they can execute today"),
            "source_citation" to Schema.string(description = "Credible scientific or clinical source, e.g. Harvard T.H. Chan, ICMR-NIN, AJCN, WHO"),
            "personalized_highlight" to Schema.string(description = "Short badge text noting why this tip was selected today based on user's stats")
        )
    )

    private val geminiModel by lazy {
        Firebase.ai.generativeModel(
            modelName = "gemini-3.8-flash",
            generationConfig = generationConfig {
                responseMimeType = "application/json"
                responseSchema = tipResponseSchema
            }
        )
    }

    suspend fun fetchDailyPersonalizedTip(
        profile: UserProfile,
        todayEntries: List<FoodDiaryEntry>,
        todayWaterMl: Int,
        dateKey: String
    ): Result<AiPersonalizedNutritionTip> {
        return try {
            val totalCalories = todayEntries.sumOf { it.calories }
            val totalProtein = todayEntries.sumOf { it.protein }.roundToInt()
            val totalCarbs = todayEntries.sumOf { it.carbohydrates }.roundToInt()
            val totalFat = todayEntries.sumOf { it.fat }.roundToInt()
            val totalFiber = todayEntries.sumOf { it.fiber }.roundToInt()

            val calorieGoal = profile.dailyCalorieGoal.coerceAtLeast(800)
            val waterGoal = profile.dailyWaterGoalMl.coerceAtLeast(1000)
            val proteinGoal = profile.effectiveProteinGoalG().coerceAtLeast(30)

            val recentMealsSummary = if (todayEntries.isEmpty()) {
                "No meals logged yet today."
            } else {
                todayEntries.take(4).joinToString(", ") { "${it.foodName} (${it.calories} kcal, ${it.protein.roundToInt()}g P)" }
            }

            val prompt = """
                You are an expert clinical dietitian and motivational nutrition coach.
                Analyze the user's real-time nutrition logs and goals for today ($dateKey) and generate exactly ONE highly personalized, science-backed Daily Nutrition Tip tailored to their progress:
                
                USER PROFILE:
                - Name: ${profile.name}
                - Fitness Goal: ${profile.fitnessGoal}
                - Dietary/Cuisine Preference: ${profile.dietaryPreference.ifBlank { "Balanced Indian & International" }}
                
                TODAY'S METRICS SO FAR:
                - Calories: $totalCalories / $calorieGoal kcal
                - Hydration: $todayWaterMl / $waterGoal ml
                - Protein: $totalProtein / $proteinGoal g
                - Carbs: $totalCarbs g, Fat: $totalFat g, Fiber: $totalFiber g
                - Meals Logged So Far: $recentMealsSummary

                INSTRUCTIONS:
                1. Make the tip genuinely personalized to their real stats (e.g. if protein is low, focus on smart protein anchors; if hydration is lagging, recommend a hydration strategy; if close to calorie budget, suggest a high-volume, low-calorie nutrient swap).
                2. Be warm, empowering, and strictly evidence-based. No extreme fad diets.
                3. The micro_action must be simple, specific, and realistic to execute today.
            """.trimIndent()

            val response = withTimeout(40_000L) {
                geminiModel.generateContent(prompt)
            }

            val jsonText = response.text ?: error("Empty response from Gemini API")
            val root = JSONObject(jsonText)

            val tip = AiPersonalizedNutritionTip(
                id = "ai_tip_${dateKey}_${System.currentTimeMillis()}",
                title = root.optString("title", "Optimize Your Daily Fuel"),
                category = root.optString("category", "Personalized Nutrition"),
                emoji = root.optString("emoji", "💡"),
                advice = root.optString("advice", "Focus on nutrient-dense whole foods to reach your goals steadily."),
                scientificRationale = root.optString("scientific_rationale", "Evidence shows nutrient-dense meal spacing stabilizes glycemic control."),
                microAction = root.optString("micro_action", "Drink 1 glass of water and add a colorful veggie to your next plate."),
                sourceCitation = root.optString("source_citation", "Harvard T.H. Chan School of Public Health"),
                personalizedHighlight = root.optString("personalized_highlight", "Personalized for ${profile.fitnessGoal}"),
                dateKey = dateKey,
                isAiGenerated = true
            )
            Result.success(tip)
        } catch (e: Exception) {
            Result.failure(e)
        }
    }
}

/**
 * Local cache to ensure we fetch exactly ONE personalized Gemini tip per calendar day,
 * persisting it across app restarts.
 */
object DailyNutritionTipCache {
    private const val PREFS_NAME = "nutriscan_daily_ai_tips_cache"
    private const val KEY_PREFIX_TIP = "cached_tip_json_"

    fun getCachedTipForDay(context: Context, dateKey: String): AiPersonalizedNutritionTip? {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val json = prefs.getString("$KEY_PREFIX_TIP$dateKey", null) ?: return null
        return try {
            val root = JSONObject(json)
            AiPersonalizedNutritionTip(
                id = root.optString("id"),
                title = root.optString("title"),
                category = root.optString("category"),
                emoji = root.optString("emoji"),
                advice = root.optString("advice"),
                scientificRationale = root.optString("scientific_rationale"),
                microAction = root.optString("micro_action"),
                sourceCitation = root.optString("source_citation"),
                personalizedHighlight = root.optString("personalized_highlight"),
                dateKey = root.optString("date_key", dateKey),
                isAiGenerated = root.optBoolean("is_ai_generated", true)
            )
        } catch (e: Exception) {
            null
        }
    }

    fun saveCachedTipForDay(context: Context, dateKey: String, tip: AiPersonalizedNutritionTip) {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val json = JSONObject().apply {
            put("id", tip.id)
            put("title", tip.title)
            put("category", tip.category)
            put("emoji", tip.emoji)
            put("advice", tip.advice)
            put("scientific_rationale", tip.scientificRationale)
            put("micro_action", tip.microAction)
            put("source_citation", tip.sourceCitation)
            put("personalized_highlight", tip.personalizedHighlight)
            put("date_key", tip.dateKey)
            put("is_ai_generated", tip.isAiGenerated)
        }.toString()
        prefs.edit().putString("$KEY_PREFIX_TIP$dateKey", json).apply()
    }
}

